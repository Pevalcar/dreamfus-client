/**
 * Report generator for SDD review
 * Produces markdown report with doubts, alternatives, and recommendations
 */

const { format: formatDate } = new Date();

/**
 * Generate the review report markdown
 * @param {Object} reviewData - Data from analysis
 * @param {string} specPath - Path to spec file
 * @param {string} planPath - Path to plan file (optional)
 * @returns {string} - Markdown formatted report
 */
function generate_report(reviewData, specPath, planPath = null) {
  const report = [];
  
  // Header
  report.push('# SDD Review Report');
  report.push('');
  report.push(`**Generated:** ${new Date().toISOString().split('T')[0]}`);
  report.push(`**Source:** ${specPath}`);
  if (planPath) {
    report.push('');
    report.push(`**Plan:** ${planPath}`);
  }
  report.push('');
  
  // Summary
  report.push('## Summary');
  report.push('');
  report.push(`- Total assumptions detected: ${reviewData.assumptions.total}`)
  report.push(`- Total doubt questions generated: ${reviewData.doubts.total_questions}`)
  report.push(`- Alternatives explored: ${reviewData.alternatives.total_alternatives}`)
  report.push('');
  
  // Assumptions Table
  if (reviewData.assumptions.assumptions.length > 0) {
    report.push('## Assumptions Detected');
    report.push('');
    report.push('| # | Texto | Severidad | Categoría | Línea |');
    report.push('|---|-------|-----------|-----------|-------|');
    
    reviewData.assumptions.assumptions.forEach((a, i) => {
      report.push(`| ${i + 1} | ${escape_md(a.text)} | ${a.severity} | ${a.category} | ${a.line} |`);
    });
    report.push('');
  }
  
  // Doubt Questions
  report.push('## Questions for Cross-Examining');
  report.push('');
  report.push('These questions are meant to stress-test your assumptions and decisions:');
  report.push('');
  
  reviewData.doubts.by_assumption.forEach((item, i) => {
    report.push(`### Assumption ${i + 1}: "${item.assumption_text.substring(0, 50)}..."`);
    report.push('');
    item.questions.forEach((q, j) => {
      report.push(`${j + 1}. ${q.text}`);
    });
    report.push('');
  });
  
  // Alternatives
  if (reviewData.alternatives.by_assumption.length > 0) {
    report.push('## Alternative Approaches');
    report.push('');
    report.push('For key decisions, consider these alternatives:');
    report.push('');
    
    reviewData.alternatives.by_assumption.forEach((item, i) => {
      report.push(`### Alternative ${i + 1}: ${item.assumption_text.substring(0, 40)}...`);
      report.push('');
      report.push(`**Categoría:** ${item.category}`);
      report.push('');
      
      item.alternatives.forEach((alt, j) => {
        report.push(`#### ${alt.name}`);
        report.push('');
        report.push(`**Approach:** ${alt.approach}`);
        report.push('');
        if (alt.pros.length > 0) {
          report.push('**Pros:**');
          alt.pros.forEach(p => report.push(`  - ${p}`));
          report.push('');
        }
        if (alt.cons.length > 0) {
          report.push('**Cons:**');
          alt.cons.forEach(c => report.push(`  - ${c}`));
          report.push('');
        }
      });
    });
  }
  
  // Recommendations
  report.push('## Recommendations');
  report.push('');
  
  const highSeverityCount = reviewData.assumptions.assumptions.filter(a => a.severity === 'high').length;
  const mediumSeverityCount = reviewData.assumptions.assumptions.filter(a => a.severity === 'medium').length;
  
  if (highSeverityCount > 0) {
    report.push(`⚠️ **Prioridad alta:** ${highSeverityCount} suposiciones de severidad alta requieren revisión inmediata.`);
    report.push('');
  }
  
  if (mediumSeverityCount > 2) {
    report.push(`⚠️ **Revisión recomendada:** ${mediumSeverityCount} suposiciones de severidad media pueden ser optimizadas.`);
    report.push('');
  }
  
  // Action Items
  report.push('## Action Items');
  report.push('');
  report.push('Before proceeding, consider addressing:');
  report.push('');
  
  let itemNum = 1;
  reviewData.assumptions.assumptions.forEach(a => {
    if (a.severity === 'high') {
      report.push(`${itemNum}. Revisa: "${a.text.substring(0, 60)}..."`);
      report.push(`   - Límite: línea ${a.line}`);
      report.push(`   - Categoría: ${a.category}`);
      itemNum++;
    }
  });
  report.push('');
  
  // Next Steps
  report.push('## Next Steps');
  report.push('');
  report.push('1. **Resuelve las dudas críticas** marcadas con ⚠️')
  report.push('2. **Documenta decisiones** en el spec o plan existente')
  report.push('3. **Re-ejecuta review** si fue necesario cambiar suposiciones')
  report.push('4. **Continua con la implementación** cuando estés seguro de las decisiones')
  report.push('');
  
  // Footer
  report.push('---');
  report.push('');
  report.push('*Generated by sdd-review - Doubt-driven development review tool*');
  report.push('');
  
  return report.join('\n');
}

/**
 * Escape markdown special characters
 * @param {string} text - Text to escape
 * @returns {string} - Escaped text
 */
function escape_md(text) {
  return text
    .replace(/\*/g, '\\*')
    .replace(/=/g, '\\=')
    .replace(/\[/g, '\\[')
    .replace(/\]/g, '\\]');
}

/**
 * Generate detailed comparison report for alternatives
 * @param {Object} alternatives - Alternative data
 * @returns {string} - Markdown formatted comparison
 */
function generate_comparison_report(alternatives) {
  const report = [];
  
  report.push('# Alternative Comparison');
  report.push('');
  
  alternatives.forEach((item, i) => {
    report.push(`## ${item.assumption_text.substring(0, 50)}...`);
    report.push('');
    
    const sorted = [...item.alternatives].sort((a, b) => b.score - a.score);
    
    report.push('| Alternativa | Score | Pros | Contras |');
    report.push('|-------------|-------|------|---------|');
    
    sorted.forEach(alt => {
      const prosCount = alt.pros.length;
      const consCount = alt.cons.length;
      report.push(`| ${alt.name} | ${alt.score} | ${prosCount} | ${consCount} |`);
    });
    report.push('');
    
    report.push(`**Recomendación:** ${sorted[0].name} (${sorted[0].score} puntos)`);
    report.push('');
  });
  
  return report.join('\n');
}

/**
 * Generate quick summary report
 * @param {Object} reviewData - Review data
 * @returns {string} - Short markdown summary
 */
function generate_summary(reviewData) {
  const lines = [];
  
  lines.push('## Quick Summary');
  lines.push('');
  lines.push(`🤔 Assumptions: ${reviewData.assumptions.total}`);
  lines.push(`❓ Questions: ${reviewData.doubts.total_questions}`);
  lines.push(`🔄 Alternatives: ${reviewData.alternatives.total_alternatives}`);
  lines.push('');
  
  // Severity breakdown
  const severityCount = reviewData.assumptions.assumptions.reduce((acc, a) => {
    acc[a.severity] = (acc[a.severity] || 0) + 1;
    return acc;
  }, {});
  
  if (severityCount.high) {
    lines.push(`⚠️ High severity: ${severityCount.high}`);
  }
  if (severityCount.medium) {
    lines.push(`⚠️ Medium severity: ${severityCount.medium}`);
  }
  
  return lines.join('\n');
}

module.exports = {
  generate_report,
  generate_comparison_report,
  generate_summary,
  escape_md
};